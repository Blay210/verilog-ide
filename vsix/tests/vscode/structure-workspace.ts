import * as vscode from 'vscode';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';

export async function run() {
  await vscode.extensions.getExtension('rtl-dev-local.rtl-dev')!.activate();
  const root = vscode.workspace.workspaceFolders![0].uri.fsPath;
  await mkdir(path.join(root,'.rtl'),{recursive:true});
  const state = () => vscode.commands.executeCommand<any>('rtl.getStructure');
  await vscode.commands.executeCommand('workbench.view.extension.rtl-structure');
  for(let i=0;i<30 && !(await state()).panelOpen;i++) await new Promise(r=>setTimeout(r,100));
  assert.equal((await state()).panelOpen,true,'Activity Bar container visibility opens the canvas');
  assert.equal((await state()).design,undefined,'Opening Structure is analysis-free');
  assert.ok(await vscode.commands.executeCommand('rtl.showStructure','basic'));
  assert.equal((await state()).viewMode,'schematic');
  assert.equal((await state()).operations.status,'supported','Default entry must analyze the schematic without another button');
  await vscode.commands.executeCommand('rtl.showScopeOperations');
  const combined = await state();
  assert.equal(combined.operations.status,'supported');
  assert.equal(combined.operations.modules.length,1);
  assert.equal(combined.operations.modules[0].instanceId,'top.dut');
  await vscode.commands.executeCommand('rtl.inspectStructure','top.dut');
  await vscode.commands.executeCommand('rtl.showInternalOperations');
  const before = await state(); assert.equal(before.operations.status,'supported');
  const source = path.join(root,'rtl/design.sv'), original = await readFile(source,'utf8');
  const doc = await vscode.workspace.openTextDocument(source);
  const offset = doc.getText().indexOf('W=4')+2;
  assert.ok(offset>1);
  const edit = new vscode.WorkspaceEdit(); edit.replace(doc.uri,new vscode.Range(doc.positionAt(offset),doc.positionAt(offset+1)),'8');
  assert.equal(await vscode.workspace.applyEdit(edit),true);
  for(let i=0;i<30 && !(await state()).stale;i++) await new Promise(r=>setTimeout(r,100));
  const changed = await state(); assert.equal(changed.stale,true);
  assert.deepEqual(changed.design,before.design,'Editing retains the last hierarchy');
  assert.deepEqual(changed.operations,before.operations,'Editing retains the last static internal graph');
  await vscode.commands.executeCommand('rtl.openStructureWorkspace');
  assert.equal((await state()).stale,true,'Re-entering does not automatically analyze');
  assert.deepEqual((await state()).design,before.design);
  assert.ok(await vscode.commands.executeCommand('rtl.refreshStructure'));
  const updated = await state(); assert.equal(updated.stale,false);
  assert.equal(updated.viewMode,'operations');assert.equal(updated.operations.status,'supported','Update retains the chosen logic view');
  const dut = updated.design.roots[0].children.find((node:any)=>node.name==='dut');
  assert.equal(dut.parameters.find((p:any)=>p.name==='W').value,'8');
  assert.equal(await readFile(source,'utf8'),original,'Update must not save dirty RTL');
  const tabs = vscode.window.tabGroups.all.flatMap(group=>group.tabs).filter(tab=>tab.input instanceof vscode.TabInputWebview && tab.label.includes('RTL Structure'));
  assert.equal(tabs.length,1,'Workspace reuse must not create duplicate panels');
  await vscode.window.tabGroups.close(tabs);
  assert.equal((await state()).panelOpen,false);
  await vscode.commands.executeCommand('rtl.openStructureWorkspace');
  assert.equal((await state()).panelOpen,true);
  assert.deepEqual((await state()).design,updated.design,'Reopening retains the analyzed hierarchy');
  assert.deepEqual((await state()).operations,updated.operations,'Reopening current view retains the static graph without analysis');
  await writeFile(path.join(root,'.rtl/structure-workspace-host.json'),JSON.stringify({passed:true,entryAnalysisFree:true,manualUpdate:true,dirtyRTL:true,retainedGraph:true,reopen:true,scopeOperations:true},null,2));
  console.log('RTL_STRUCTURE_WORKSPACE_PASS');
}
