import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';
import { root, inside } from './environment.mjs';

/** Owned built-in only. All metadata/grammar assets use the guarded source overlay. */
export async function prepareLanguage(source = path.join(root, 'upstream')) {
  if (!inside(root, fs.realpathSync(source))) throw Error('Language target escaped IDE.');
  const directory = path.join(source, 'extensions/rtl-language');
  if (!inside(source, fs.realpathSync(directory))) throw Error('Language target escaped source.');
  const target = path.join(directory, 'dist/extension.cjs');
  const server = path.join(directory, 'dist/server.cjs');
  const marker = '// RTL IDE owned lexical bundle; generated by prepare-language.mjs';
  if (fs.existsSync(path.dirname(target)) && !inside(directory, fs.realpathSync(path.dirname(target)))) throw Error('Language bundle directory escaped.');
  if (fs.existsSync(target) && (!inside(directory, fs.realpathSync(target)) || !fs.readFileSync(target, 'utf8').startsWith(marker))) throw Error('Unmanaged language bundle; refusing overwrite.');
  if (fs.existsSync(server) && (!inside(directory, fs.realpathSync(server)) || !fs.readFileSync(server, 'utf8').startsWith(marker))) throw Error('Unmanaged language server; refusing overwrite.');
  await build({ entryPoints: [path.join(root, 'language/src/extension.ts')], outfile: target,
    bundle: true, platform: 'node', format: 'cjs', target: 'node22', external: ['vscode'],
    legalComments: 'inline', banner: { js: marker } });
  await build({ entryPoints: [path.join(root, 'language/src/server.ts')], outfile: server,
    bundle: true, platform: 'node', format: 'cjs', target: 'node22',
    legalComments: 'inline', banner: { js: marker } });
}
