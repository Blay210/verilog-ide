import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';
import { root, inside } from './environment.mjs';
import { randomBytes } from 'node:crypto';

/** Development-only owned bundle, never a sibling project or user-extension input. */
export async function prepareRuntime(source = path.join(root, 'upstream')) {
  if (!inside(root, fs.realpathSync(source))) throw Error('Runtime source escaped IDE.');
  const directory = path.join(source, 'out/vs/platform/rtl/node');
  let ancestor = directory;
  while (!fs.existsSync(ancestor)) ancestor = path.dirname(ancestor);
  if (!inside(source, fs.realpathSync(ancestor))) throw Error('Runtime target escaped source.');
  const target = path.join(directory, 'runtime.js');
  const importBridge = path.join(directory, 'analyze.py');
  const bridgeMarker = '# RTL IDE owned import semantic bridge\n';
  if (fs.existsSync(importBridge) && (!inside(source, fs.realpathSync(importBridge)) || !fs.readFileSync(importBridge, 'utf8').startsWith(bridgeMarker))) throw Error('Unmanaged import semantic bridge.');
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(importBridge, bridgeMarker + fs.readFileSync(path.join(root, 'language/python/analyze.py'), 'utf8'));
  const marker = '// RTL IDE owned runtime bundle; generated by prepare-runtime.mjs';
  if (fs.existsSync(target) && (!inside(source, fs.realpathSync(target)) || !fs.readFileSync(target, 'utf8').startsWith(marker))) throw Error('Unmanaged runtime target; refusing overwrite.');
  await build({ entryPoints: [path.join(root, 'runtime/host.ts')], outfile: target, bundle: true,
    platform: 'node', format: 'esm', target: 'node22', legalComments: 'inline',
    banner: { js: marker + '\nimport { createRequire as rtlCreateRequire } from "node:module"; const require = rtlCreateRequire(import.meta.url);' }
  });
  const worker = path.join(directory, 'waveform-worker.cjs'), htmlFile = path.join(directory, 'waveform.html');
  for (const file of [worker, htmlFile]) {
    if (fs.existsSync(file) && (!inside(source, fs.realpathSync(file)) || !fs.readFileSync(file, 'utf8').startsWith(file === htmlFile ? `<!--${marker}-->` : marker))) throw Error('Unmanaged waveform target; refusing overwrite.');
  }
  await build({ entryPoints: [path.join(root, 'runtime/waveform/worker.ts')], outfile: worker, bundle: true, platform: 'node', format: 'cjs', target: 'node22', banner: { js: marker } });
  const [client, bridge, template] = await Promise.all([
    build({ entryPoints: [path.join(root, 'waveform-ui/waveform.ts')], bundle: true, write: false, platform: 'browser', format: 'iife', target: 'es2022' }),
    build({ entryPoints: [path.join(root, 'waveform-ui/bridge.ts')], bundle: true, write: false, platform: 'browser', format: 'iife', target: 'es2022' }),
    build({ entryPoints: [path.join(root, 'waveform-ui/html.ts')], bundle: true, write: false, platform: 'node', format: 'esm' })
  ]);
  const { waveformHtml } = await import('data:text/javascript;base64,' + Buffer.from(template.outputFiles[0].text).toString('base64'));
  const nonce = randomBytes(18).toString('base64');
  let html = waveformHtml('RTL_SCRIPT', 'RTL_CSS', "'unsafe-inline'", nonce);
  const script = (bridge.outputFiles[0].text + '\n' + client.outputFiles[0].text).replace(/<\/script/gi, '<\\/script');
  const css = fs.readFileSync(path.join(root, 'waveform-ui/waveform.css'), 'utf8') + '\n#external{display:none}';
  html = html.replace('<link rel="stylesheet" href="RTL_CSS">', `<style>${css}</style>`)
    .replace(`<script nonce="${nonce}" src="RTL_SCRIPT"></script>`, `<script nonce="${nonce}">${script}</script>`);
  // Leading comment identifies our generated asset without permitting arbitrary file reads.
  fs.writeFileSync(htmlFile, `<!--${marker}-->\n` + html);
}
