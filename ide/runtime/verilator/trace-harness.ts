import type { WaveformFormat } from '../core/model';

/** Own generated C++ driver, using Verilator's public timing and trace APIs.
 * No source rewriting, wrapper module or user-authored C++ requirement.
 */
export function managedTraceHarness(format: WaveformFormat, filename: string, timing = true): string {
  if (!['vcd', 'fst', 'none'].includes(format)) throw Error('Unsupported managed trace format.');
  if (format !== 'none' && (!/^[A-Za-z_][A-Za-z0-9_$.-]{0,127}\.(vcd|fst)$/.test(filename) || !filename.endsWith('.' + format))) throw Error('Managed trace filename must be a safe local filename of the selected format.');
  const trace = format !== 'none';
  const className = format === 'fst' ? 'VerilatedFstC' : 'VerilatedVcdC';
  return `// Generated by RTL IDE. Original source is unchanged.
#include "Vrtl.h"
#include "verilated.h"
#include <memory>
${trace ? `#include "verilated_${format}_c.h"` : ''}
int main(int argc, char** argv) {
    const auto context = std::make_unique<VerilatedContext>();
    context->threads(1);
    context->commandArgs(argc, argv);
    ${trace ? 'context->traceEverOn(true);' : ''}
    const auto model = std::make_unique<Vrtl>(context.get(), "");
    ${trace ? `const auto trace = std::make_unique<${className}>();
    model->trace(trace.get(), 99);
    trace->open("${filename}");` : ''}
    while (!context->gotFinish()) {
        model->eval();
        ${trace ? 'trace->dump(context->time());' : ''}
        ${timing ? 'if (context->gotFinish() || !model->eventsPending()) break;\n        context->time(model->nextTimeSlot());' : 'context->timeInc(1);'}
    }
    model->final();
    ${trace ? 'trace->close();' : ''}
    return 0;
}
`;
}
