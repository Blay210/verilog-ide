const selected = (host, tops) => ({ ids: host.state.review.inventory.tops.filter(top => tops.includes(top.top) && top.file.startsWith('verification/')).map(top => top.id) });

test('refresh requested after an active scan sampled sources waits for a coalesced fresh scan', async t => {
  const { dir, host } = await fixture(t);
  const service = host.service;
  const inspect = service.inspect.bind(service);
  let enter, release;
  const entered = new Promise(resolve => { enter = resolve; });
  const gate = new Promise(resolve => { release = resolve; });
  let sampled = false;
  service.inspect = async (...args) => { if (!sampled) { sampled = true; enter(); await gate; } return inspect(...args); };
  const first = host.refreshInputs();
  await entered;
  await fs.writeFile(path.join(dir, 'rtl/after-sample.sv'), 'module after_sample; endmodule\n');
  const following = [host.refreshInputs(), host.refreshInputs()];
  release();
  await first; await Promise.all(following);
  assert.equal(host.state.sourceSync.state, 'changed');
  assert.ok(host.state.sourceSync.added.includes('rtl/after-sample.sv'));
});
test('actual slang management adds/removes tops, rediscovers sources/packages/headers and preserves history/name/settings', async t => {
  const { dir, host } = await fixture(t);
  host.start(['tb.first'], true);
  while (host.state.phase === 'running') await new Promise(resolve => setTimeout(resolve, 5));
  const oldRun = host.state.tests[0].latest.runId;
  await fs.writeFile(path.join(dir, 'rtl/constants.sv'), 'package constants; parameter int WIDTH=7; endpackage\n');
  await fs.writeFile(path.join(dir, 'rtl/helper.sv'), 'module helper; logic [constants::WIDTH-1:0] x; endmodule\n');
  await fs.writeFile(path.join(dir, 'rtl/defs.svh'), '`define FLAG 1\n');
  await fs.appendFile(path.join(dir, 'verification/tb.sv'), 'module third; endmodule\n');
  const before = await fs.readFile(path.join(dir, 'rtl.toml'));
  await host.refreshInputs();
  assert.equal(host.state.sourceSync.state, 'changed');
  assert.ok(host.state.sourceSync.added.includes('rtl/helper.sv'));
  // A folder TB is now registered by discovery, without waiting for Apply.
  const thirdName = host.state.tests.find(test => test.top === 'third').name;
  assert.ok(!host.state.sourceSync.candidates.some(name => name.endsWith('.third')));
  assert.deepEqual(await fs.readFile(path.join(dir, 'rtl.toml')), before);
  await assert.rejects(host.manageProject(false), /신뢰/);
  await host.manageProject(true); assert.ok(host.state.review.execution);
  assert.deepEqual(await fs.readFile(path.join(dir, 'rtl.toml')), before);
  await assert.rejects(host.saveReview(true), /테스트 목록/);
  await host.confirmReview(selected(host, ['first','third']), true);
  assert.equal(host.state.error, undefined);
  assert.equal(host.state.sourceSync.state, 'matching');
  const reopened = new SimulationHostSession(() => {}); t.after(() => reopened.close());
  await reopened.inspect(dir);
  assert.deepEqual(reopened.state.savedFolderRoles, host.state.savedFolderRoles);
  assert.deepEqual(host.state.tests.map(test => test.name), ['tb.first',thirdName]);
  assert.equal(host.state.tests[0].latest.runId, oldRun);
  assert.equal(host.state.history[0].runId, oldRun);
  const project = await loadProject(dir);
  assert.ok(project.sources[0].endsWith('constants.sv'));
  assert.ok(project.sources.some(file => file.endsWith('helper.sv')));
  assert.equal(project.defines.FEATURE, '1'); assert.ok(project.includeDirs.some(file => file.endsWith('rtl')));
  const cli = spawnSync(process.execPath, [path.join(root, 'scripts/rtl.mjs'), 'check'], { cwd: dir, encoding: 'utf8' });
  assert.equal(cli.status, 0, cli.stderr);
  assert.deepEqual(JSON.parse(cli.stdout).tests.map(test => test.name), ['tb.first',thirdName]);
  await host.manageProject(true); await host.confirmReview({ ids: [] }, true);
  assert.equal(host.state.error, undefined); assert.equal(host.state.tests.length, 0);
  assert.equal((await readImportedExecution(dir)).preview.tests.length, 0);
  assert.equal((await readHistory(dir))[0].runId, oldRun);
  assert.equal(await fs.readFile(path.join(dir, 'rtl/helper.sv'), 'utf8'), 'module helper; logic [constants::WIDTH-1:0] x; endmodule\n');
});
test('manual/ordinary manifests, stale revision and compiler failure never get overwritten', async t => {
  const { dir, host } = await fixture(t);
  const file = path.join(dir, 'rtl.toml'), bytes = await fs.readFile(file);
  await host.manageProject(true);
  await fs.writeFile(path.join(dir, 'rtl/broken.sv'), 'module broken; missing_type value; endmodule\n');
  await host.confirmReview(selected(host, ['first']), true);
  assert.ok(host.state.error); assert.deepEqual(await fs.readFile(file), bytes);
  await fs.unlink(path.join(dir, 'rtl/broken.sv'));
  await host.inspect(dir); await host.manageProject(true);
  await fs.appendFile(file, '# user edit\n');
  await host.confirmReview(selected(host, ['first']), true); assert.ok(host.state.error);
  assert.equal(await fs.readFile(file, 'utf8'), bytes.toString() + '# user edit\n');
  await host.inspect(dir); await host.manageProject(true); assert.ok(host.state.error); assert.equal(host.state.review, undefined);
  await host.refreshInputs(); assert.equal(host.state.sourceSync.state, 'unavailable');
  assert.deepEqual(host.state.savedFolderRoles.folders, [{ path: 'verification', role: 'simulation' }]);
  assert.equal(await fs.readFile(file, 'utf8'), bytes.toString() + '# user edit\n');
  await fs.writeFile(file, bytes.toString().replace('# RTL IDE imported execution project v1\n', ''));
  await host.inspect(dir); await host.manageProject(true); assert.match(host.state.error, /보존/);
  assert.equal(host.state.review, undefined);
  await host.refreshInputs(); assert.equal(host.state.sourceSync.state, 'protected');
  assert.deepEqual(host.state.savedFolderRoles.folders, [{ path: 'verification', role: 'simulation' }]);
  assert.deepEqual((await fs.readdir(path.join(dir, '.rtl'))).filter(file => file.endsWith('.lock') || file.endsWith('.tmp')), []);
});
test('management repairs a deleted registered source and keeps existing test identity when a basename collision appears', async t => {
  const { dir, host } = await fixture(t);
  await fs.mkdir(path.join(dir, 'verification/other'));
  await fs.writeFile(path.join(dir, 'verification/other/tb.sv'), 'module first; endmodule\n');
  await host.manageProject(true);
  const ids = host.state.review.inventory.tops.filter(top => top.top === 'first').map(top => top.id);
  await host.confirmReview({ ids }, true); assert.equal(host.state.error, undefined);
  assert.ok(host.state.tests.some(test => test.name === 'tb.first'));
  const additional = host.state.tests.find(test => test.name !== 'tb.first'); assert.match(additional.name, /^tb.first-/);
  await fs.unlink(path.join(dir, 'verification/tb.sv'));
  await host.refreshInputs(); assert.equal(host.state.sourceSync.state, 'matching');
  assert.ok(!host.state.tests.some(test => test.name === 'tb.first'));
  await host.inspect(dir); assert.equal(host.state.phase, 'idle');
  assert.equal(host.state.sourceSync.state, 'matching');
  await host.manageProject(true); assert.ok(host.state.review.execution);
  await host.confirmReview(selected(host, ['first']), true); assert.equal(host.state.error, undefined);
  assert.equal(host.state.tests.length, 1); assert.equal(host.state.tests[0].name, additional.name);
});
test('cancelled/locked/read-only management leaves manifest and history intact', async t => {
  const { dir, host, provider } = await fixture(t);
  await host.manageProject(true);
  const review = host.state.review, request = selected(host, ['first']);
  const file = path.join(dir, 'rtl.toml'), bytes = await fs.readFile(file);
  const controller = new AbortController(); controller.abort();
  await assert.rejects(confirmImportSettings(review, request, provider, controller.signal), /abort/i);
  const lock = path.join(dir, '.rtl/import-review.lock'); await fs.writeFile(lock, 'another owner');
  await assert.rejects(confirmImportSettings(review, request, provider), /busy/); await fs.unlink(lock);
  await fs.chmod(file, 0o444);
  try { await assert.rejects(confirmImportSettings(review, request, provider), /read-only|EPERM|EACCES/); } finally { await fs.chmod(file, 0o666); }
  assert.deepEqual(await fs.readFile(file), bytes);
  assert.deepEqual((await fs.readdir(path.join(dir, '.rtl'))).filter(file => file.endsWith('.lock') || file.endsWith('.tmp')), []);
});
