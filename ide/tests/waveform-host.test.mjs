import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { root } from '../scripts/environment.mjs';
import { prepareRuntime } from '../scripts/prepare-runtime.mjs';
const require = createRequire(import.meta.url);
const { createProject, readHistory } = require('../dist/runtime/core/index.js');
const { SimulationService } = require('../dist/runtime/simulation.js');
const { WaveformHost } = require('../dist/runtime/waveform-host.js');
const vcd = '$timescale 1ns $end\n$scope module tb $end\n$var wire 1 ! clk $end\n$upscope $end\n$enddefinitions $end\n#0\n0!\n#5\n1!\n#10\n0!\n';
test('owned waveform worker verifies retained run, preserves snapshot, bounds readers and terminates queries', async t => {
  const dir = await fs.mkdtemp(path.join(root, '.dev/wave-host-'));
  t.after(() => fs.rm(dir, { recursive: true, force: true }));
  await prepareRuntime(dir); await createProject(dir, true);
  let trace = vcd;
  const service = new SimulationService(async () => ({ id: 'verilator', capabilities: { waveforms: ['vcd'], timing: true, inputSnapshot: true }, check: async () => {}, build: async ({ directory }) => ({ executable: 'fixture', cwd: directory }), run: async artifact => { await fs.writeFile(path.join(artifact.cwd, 'wave.vcd'), trace); } }));
  await service.run({ root: dir, names: ['counter_basic'] });
  const result = (await readHistory(dir))[0];
  const waves = new WaveformHost(path.join(dir, 'out/vs/platform/rtl/node/waveform-worker.cjs'));
  t.after(() => waves.dispose());
  const doc = await waves.open(result);
  assert.equal(doc.runId, result.runId); assert.equal(doc.metadata.signals.length, 1);
  const html = await fs.readFile(path.join(dir, 'out/vs/platform/rtl/node/waveform.html'), 'utf8');
  assert.match(html, /rtlWaveform/); assert.doesNotMatch(html, /src="RTL_SCRIPT"|href="RTL_CSS"/);
  const request = { signals: [doc.metadata.signals[0].id], from: '0', to: '10', cursor: '5', pixels: 600 };
  assert.equal((await waves.query({ token: doc.token, kind: 'window', request })).rows[0].value, '1');
  // A new simulation has its own trace; an open old reader must not follow latest.
  trace = vcd.replace('1!', '0!');
  await service.run({ root: dir, names: ['counter_basic'] });
  const nextResult = (await readHistory(dir)).find(item => item.runId !== result.runId);
  assert.ok(nextResult); assert.notEqual(nextResult.waveform, result.waveform);
  const nextDoc = await waves.open(nextResult);
  assert.equal((await waves.query({ token: nextDoc.token, kind: 'values', request })).rows[0].value, '0');
  assert.equal((await waves.query({ token: doc.token, kind: 'values', request })).rows[0].value, '1');
  assert.equal(await fs.readFile(result.waveform, 'utf8'), vcd);
  await waves.close(nextDoc.token);
  await fs.writeFile(result.waveform, vcd.replace('1!', '0!'));
  // Existing reader remains a snapshot; future opens refuse modified recorded bytes.
  assert.equal((await waves.query({ token: doc.token, kind: 'values', request })).rows[0].value, '1');
  await assert.rejects(waves.open(result), /modified/);
  await fs.writeFile(result.waveform, vcd);
  await assert.rejects(waves.open({ ...result, waveform: 'wave.fst' }), /VCD/);
  for (let i = 0; i < 3; i++) await waves.open(result);
  await assert.rejects(waves.open(result), /maximum 4/);
  await assert.rejects(waves.query({ token: doc.token, kind: 'window', request: { ...request, to: '999' } }), /Invalid/);
  await waves.close(doc.token); await assert.rejects(waves.query({ token: doc.token, kind: 'window', request }), /closed/);
  await waves.dispose(); await assert.rejects(waves.open(result), /unavailable/);
});
